#!/usr/bin/env python3
"""Test lab A: start an official mosquitto broker for MQTT Panel to connect to.

Five modes, each with the certificates and files generated for you:

  plain         no TLS, no password                          (default port 1883)
  tls           TLS, server certificate from a private CA    (default port 8883)
  tls-password  tls + username and password
  mtls          tls + the broker requires a client certificate
  self-signed   TLS with a self-signed server certificate, no CA: trust it by fingerprint

Examples
  python3 mosquitto_broker.py plain
  python3 mosquitto_broker.py mtls --port 18883
  python3 mosquitto_broker.py tls-password --user demo --password secret --seed

The script prints exactly what to enter in the app (New connection > Another broker)
and which files to pick with Browse. Ctrl-C stops the broker. Files go to
tools/testlab/out/<mode>/ (git-ignored) and are regenerated on every start unless --keep.
"""
from __future__ import annotations

import argparse
import json
import os
import secrets
import shutil
import signal
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from labcerts import Lab, default_hosts, fingerprint  # noqa: E402

MODES = ["plain", "tls", "tls-password", "mtls", "self-signed"]
EXTRA_BIN_DIRS = [
    "/opt/homebrew/sbin", "/opt/homebrew/bin", "/usr/local/sbin", "/usr/local/bin", "/usr/sbin",
    r"C:\Program Files\mosquitto", r"C:\Program Files (x86)\mosquitto",
]


def find_bin(name: str) -> str:
    p = shutil.which(name)
    if p:
        return p
    for d in EXTRA_BIN_DIRS:
        for cand in (Path(d) / name, Path(d) / f"{name}.exe"):
            if cand.exists():
                return str(cand)
    raise SystemExit(
        f"{name} not found. Install mosquitto first: macOS 'brew install mosquitto', "
        "Debian/Ubuntu 'sudo apt install mosquitto mosquitto-clients', Windows https://mosquitto.org/download/")


def write_passwd(passwd_bin: str, path: Path, user: str, password: str) -> None:
    if path.exists():
        path.unlink()
    subprocess.run([passwd_bin, "-b", "-c", str(path), user, password], check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def build_conf(mode: str, port: int, out: Path, ws_port: int | None) -> str:
    lines = [
        "# generated by mosquitto_broker.py, do not edit",
        "per_listener_settings false",
        "log_dest stdout",
        "log_type error", "log_type warning", "log_type notice", "log_type information",
        "connection_messages true",
        "max_queued_messages 10000",
        f"listener {port} 0.0.0.0",
        "protocol mqtt",
    ]
    tls = mode != "plain"
    if tls:
        lines += [
            f"certfile {out / 'server.pem'}",
            f"keyfile {out / 'server-key.pem'}",
            "tls_version tlsv1.2",
        ]
        if mode == "mtls":
            lines += [f"cafile {out / 'ca.pem'}", "require_certificate true", "use_identity_as_username false"]
        elif mode == "self-signed":
            # mosquitto wants cafile or capath with certfile; the self-signed cert is its own CA.
            lines += [f"cafile {out / 'server.pem'}"]
        else:
            lines += [f"cafile {out / 'ca.pem'}"]
    if mode == "tls-password":
        lines += ["allow_anonymous false", f"password_file {out / 'passwd'}"]
    else:
        lines += ["allow_anonymous true"]
    if ws_port:
        lines += [f"listener {ws_port} 0.0.0.0", "protocol websockets"]
        if tls:
            lines += [f"certfile {out / 'server.pem'}", f"keyfile {out / 'server-key.pem'}"]
            if mode != "self-signed":
                lines += [f"cafile {out / 'ca.pem'}"]
            if mode == "mtls":
                lines += ["require_certificate true"]
    return "\n".join(lines) + "\n"


def seed_messages(host: str, port: int, mode: str, out: Path, user: str | None, password: str | None,
                  p12_password: str | None) -> None:
    """Publish a few retained demo topics so the Explorer is not empty."""
    try:
        import paho.mqtt.client as mqtt
    except ImportError:
        print("  (seed skipped: pip install paho-mqtt)")
        return
    import ssl
    c = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2, protocol=mqtt.MQTTv5)
    if mode != "plain":
        ctx = ssl.create_default_context()
        ctx.load_verify_locations(str(out / ("server.pem" if mode == "self-signed" else "ca.pem")))
        if mode == "mtls":
            ctx.load_cert_chain(str(out / "client.pem"), str(out / "client-key.pem"))
        c.tls_set_context(ctx)
    if user:
        c.username_pw_set(user, password)
    c.connect(host, port, keepalive=30)
    c.loop_start()
    demo = {
        "mqttpanel-lab/site/name": "Test lab",
        "mqttpanel-lab/site/info": json.dumps({"broker": "mosquitto", "mode": mode, "seeded": True}),
        "mqttpanel-lab/sensors/hall/climate": json.dumps({"temperature": 21.5, "humidity": 48, "online": True}),
        "mqttpanel-lab/meters/1/energy": json.dumps({"power_w": 1234.5, "total_kwh": 8842.1, "phase": "L1"}),
    }
    for t, p in demo.items():
        c.publish(t, p, qos=1, retain=True).wait_for_publish(5)
    c.loop_stop()
    c.disconnect()
    print(f"  seeded {len(demo)} retained topics under mqttpanel-lab/")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", choices=MODES, nargs="?", default="plain")
    ap.add_argument("--port", type=int, help="listener port (default 1883, or 8883 with TLS)")
    ap.add_argument("--ws-port", type=int, help="also open a WebSocket listener on this port")
    ap.add_argument("--host", action="append", default=[],
                    help="extra host name or IP to put in the server certificate (repeatable)")
    ap.add_argument("--user", default="lab", help="username for tls-password (default: lab)")
    ap.add_argument("--password", help="password for tls-password (default: generated)")
    ap.add_argument("--p12-password", help="also export the client certificate as client.p12 with this passphrase")
    ap.add_argument("--out", type=Path, help="output folder (default: tools/testlab/out/<mode>)")
    ap.add_argument("--keep", action="store_true", help="reuse certificates already in the output folder")
    ap.add_argument("--seed", action="store_true", help="publish a few retained demo topics after start")
    ap.add_argument("--verbose", action="store_true", help="mosquitto -v (every packet in the log)")
    a = ap.parse_args()

    mode = a.mode
    tls = mode != "plain"
    port = a.port or (8883 if tls else 1883)
    out = (a.out or HERE / "out" / mode).resolve()
    mosq = find_bin("mosquitto")
    out.mkdir(parents=True, exist_ok=True)

    have = all((out / f).exists() for f in ["server.pem", "server-key.pem"]) and (
        mode == "self-signed" or (out / "ca.pem").exists())
    lab = Lab(out)
    if tls and not (a.keep and have):
        for f in out.glob("*.pem"):
            f.unlink()
        hosts = default_hosts(a.host)
        if mode == "self-signed":
            lab.make_self_signed_server(hosts)
        else:
            lab.make_ca()
            lab.make_server(hosts)
            lab.make_client("lab-client", p12_password=a.p12_password)
    alphabet = "abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    password = a.password or "".join(secrets.choice(alphabet) for _ in range(16))
    if mode == "tls-password":
        write_passwd(find_bin("mosquitto_passwd"), out / "passwd", a.user, password)
        (out / "password.txt").write_text(f"{a.user}\n{password}\n")

    conf = out / "mosquitto.conf"
    conf.write_text(build_conf(mode, port, out, a.ws_port))

    # ---- summary for the app --------------------------------------------
    from cryptography import x509
    print(f"\nmosquitto {mode} on port {port}" + (f", WebSocket on {a.ws_port}" if a.ws_port else ""))
    print(f"files: {out}")
    print("\nIn MQTT Panel: Connect > New connection > Another broker")
    print(f"  Host            localhost        Port  {port}")
    print(f"  Encryption      {'on (TLS)' if tls else 'off'}")
    if mode in ("tls", "tls-password", "mtls"):
        print(f"  CA certificate  Browse > {out / 'ca.pem'}")
    if mode == "mtls":
        print(f"  Client cert     Browse > {out / 'client.pem'}")
        print(f"  Client key      Browse > {out / 'client-key.pem'}")
        if a.p12_password:
            print(f"  or PKCS#12      Browse > {out / 'client.p12'}  (passphrase: {a.p12_password})")
    if mode == "self-signed":
        cert = x509.load_pem_x509_certificate((out / "server.pem").read_bytes())
        print("  No CA file. On Test or Connect the app shows the trust prompt; compare the fingerprint:")
        print(f"  SHA-256         {fingerprint(cert)}")
        print("  then choose 'Trust this certificate'.")
    if mode == "tls-password":
        print(f"  Username        {a.user}")
        print(f"  Password        {password}")
    if a.ws_port:
        print(f"  WebSocket       {'wss' if tls else 'ws'}://localhost:{a.ws_port}")
    print("\nCommand-line check (another terminal):")
    sub = [find_bin("mosquitto_sub"), "-h", "localhost", "-p", str(port), "-t", "'#'", "-v"]
    if mode in ("tls", "tls-password", "mtls"):
        sub += ["--cafile", str(out / "ca.pem")]
    if mode == "self-signed":
        sub += ["--cafile", str(out / "server.pem")]
    if mode == "mtls":
        sub += ["--cert", str(out / "client.pem"), "--key", str(out / "client-key.pem")]
    if mode == "tls-password":
        sub += ["-u", a.user, "-P", password]
    print("  " + " ".join(sub))
    print("\nCtrl-C stops the broker.\n")

    args = [mosq, "-c", str(conf)]
    if a.verbose:
        args.append("-v")
    proc = subprocess.Popen(args)

    def on_term(*_):
        raise KeyboardInterrupt
    signal.signal(signal.SIGTERM, on_term)
    try:
        time.sleep(0.8)
        if proc.poll() is not None:
            print(f"mosquitto exited with code {proc.returncode}; see the log above", file=sys.stderr)
            return 1
        if a.seed:
            try:
                seed_messages("localhost", port, mode, out, a.user if mode == "tls-password" else None,
                              password if mode == "tls-password" else None, a.p12_password)
            except Exception as e:  # noqa: BLE001
                print(f"  seed failed: {e}")
        proc.wait()
    except KeyboardInterrupt:
        pass
    finally:
        if proc.poll() is None:
            proc.send_signal(signal.SIGINT if os.name != "nt" else signal.CTRL_C_EVENT)
            try:
                proc.wait(5)
            except subprocess.TimeoutExpired:
                proc.kill()
    return 0


if __name__ == "__main__":
    sys.exit(main())
